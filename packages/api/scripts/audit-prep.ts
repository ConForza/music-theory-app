import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { createApp } from "../src/app.ts";
import { loadCourse } from "../src/course.ts";
import { openDb } from "../src/db.ts";
import { gradeOutcomes, outcomeImportance, probeOutcomes } from "../src/prep-blueprint.ts";
import { DEFAULT_PREP } from "../src/prep-config.ts";
import { generatorTemplateIds } from "@mtp/engine";

/**
 * Brief 10 audit of practice-examination coverage and variation. For every grade it plans a paper from each of several fixed seeds
 * (each for a fresh learner, so the papers are independent) and reports, from what was really generated:
 *   - every syllabus outcome of the grade is asked `itemsPerOutcome` times, in every paper (a gap exits 1);
 *   - the balance across domains, and the templates and question types used;
 *   - variation: how much of one paper reappears in another (question identity, ignoring seed), and how many templates differ;
 *   - the placement probes: which outcomes each grade's probe asks and why (how much later learning depends on them).
 * Usage: tsx scripts/audit-prep.ts [--write] [grade ...]. `--write` also writes docs/curriculum/PRACTICE_EXAM_COVERAGE.md. Deterministic.
 */
const args = process.argv.slice(2);
const write = args.includes("--write");
const grades = args.filter((a) => /^\d$/.test(a)).map(Number);
const SEEDS = [11, 23, 37, 53, 71, 89];
const course = loadCourse();
const generatable = new Set(generatorTemplateIds(course.ix));
const importance = outcomeImportance(course);
let failed = 0;
const out: string[] = [];
const say = (s = "") => (out.push(s), console.log(s));

say("# Practice examination coverage and variation");
say();
say("> *Generated by `npm run audit:prep -w @mtp/api -- --write`. Do not edit by hand.*");
say();
say(`Each grade's practice examination is planned from ${SEEDS.length} fixed seeds, each for a fresh learner, from the real curriculum. Product defaults used: ${DEFAULT_PREP.exam.itemsPerOutcome} questions per outcome, ${DEFAULT_PREP.exam.scoreReadingItems} score-reading questions, ${DEFAULT_PREP.exam.secondsPerQuestion} s per question for the optional timer (a product default, not an ABRSM time allowance). Nothing here describes ABRSM's own papers.`);
say();
say("| Grade | Questions | Outcomes | Outcomes covered in every paper | Score-reading | Mean overlap between two papers | Papers whose templates differ at a position |");
say("|---:|---:|---:|---:|---:|---:|---:|");
const details: string[] = [];
for (const grade of grades.length ? grades : [1, 2, 3, 4, 5]) {
  const papers: Array<Array<{ key: string; template: string; outcome: string | null; combined: boolean; domain: string }>> = [];
  const times: number[] = [];
  const bp = createApp({ db: openDb(":memory:"), course }).prep.blueprint(grade);
  const outcomes = gradeOutcomes(course, grade);
  for (const seed of SEEDS) {
    const db = openDb(":memory:");
    const app = createApp({ db, course });
    const u = app.fetch(new Request("http://a/api/auth/guest", { method: "POST", headers: { "content-type": "application/json" }, body: "{}" })).then((r) => r.json());
    const userId = ((await u) as { user: { id: string } }).user.id;
    const t = Date.now();
    const items = app.prep.planExam(userId, grade, seed);
    times.push(Date.now() - t);
    papers.push(items.map((i) => ({ key: i.questionKey, template: i.templateId, outcome: i.outcomeId, combined: i.combined, domain: course.ix.outcomes.get(i.outcomeId ?? "")?.domain ?? "context" })));
  }
  const bad: string[] = [];
  for (const [p, paper] of papers.entries()) {
    for (const o of outcomes) {
      const n = paper.filter((i) => i.outcome === o.id).length;
      if (n !== DEFAULT_PREP.exam.itemsPerOutcome) bad.push(`seed ${SEEDS[p]}: ${o.id} has ${n} questions`);
    }
    if (paper.filter((i) => i.combined).length !== DEFAULT_PREP.exam.scoreReadingItems) bad.push(`seed ${SEEDS[p]}: score-reading count`);
    if (new Set(paper.map((i) => i.key)).size !== paper.length) bad.push(`seed ${SEEDS[p]}: a question appears twice`);
  }
  if (bp.uncovered.length) bad.push(`uncovered: ${bp.uncovered.join(", ")}`);
  let overlap = 0;
  let differs = 0;
  let pairs = 0;
  for (let a = 0; a < papers.length; a++) {
    for (let b = a + 1; b < papers.length; b++) {
      const ka = new Set(papers[a]!.map((i) => i.key));
      overlap += papers[b]!.filter((i) => ka.has(i.key)).length / papers[b]!.length;
      differs += papers[a]!.filter((i, k) => i.template !== papers[b]![k]!.template).length / papers[a]!.length;
      pairs++;
    }
  }
  failed += bad.length;
  say(`| ${grade} | ${bp.totalItems} | ${outcomes.length} | ${bad.length ? `**NO** (${bad.length})` : `${outcomes.length} of ${outcomes.length}`} | ${DEFAULT_PREP.exam.scoreReadingItems} | ${Math.round((100 * overlap) / pairs)}% | ${Math.round((100 * differs) / pairs)}% |`);
  console.error(`  (grade ${grade}: planning ${Math.round(times.reduce((x, y) => x + y, 0) / times.length)} ms per paper)`);
  const byDomain = new Map<string, number>();
  for (const i of papers[0]!) byDomain.set(i.domain, (byDomain.get(i.domain) ?? 0) + 1);
  const tpl = new Map<string, number>();
  for (const paper of papers) for (const i of paper) tpl.set(i.template.replace(/^t\.g\d\./, ""), (tpl.get(i.template.replace(/^t\.g\d\./, "")) ?? 0) + 1);
  details.push(`### Grade ${grade}`, "", `Questions per domain in one paper: ${[...byDomain].sort().map(([d, n]) => `${d} ${n}`).join(", ")}.`, "", `Templates used across the ${SEEDS.length} papers (count): ${[...tpl].sort((a, b) => b[1] - a[1]).map(([t, n]) => `${t} ${n}`).join(", ")}.`, "");
  for (const b of bad) details.push(`- **PROBLEM:** ${b}`);
  if (bad.length) details.push("");
}
say();
say("Mean overlap is the share of one paper's questions (same music and answer, whatever the seed) that reappear in another paper: low means a new paper is genuinely new. \"Templates differ\" is how often the same position in two papers asks a different kind of question.");
say();
say("## Detail");
say();
for (const d of details) say(d);
say("## Placement probes");
say();
say(`A placement probe has ${DEFAULT_PREP.placement.probeItems} questions per grade (Grades ${DEFAULT_PREP.placement.probeGrades.join(", ")}), one per outcome, chosen by how much later learning depends on the outcome (the number of later-grade concepts that rest on it, from the prerequisite graph), with a discount for each further outcome from the same domain.`);
say();
say("| Grade | Outcome | Domain | Later concepts that depend on it | Statement |");
say("|---:|---|---|---:|---|");
for (const g of DEFAULT_PREP.placement.probeGrades) for (const o of probeOutcomes(course, g, DEFAULT_PREP.placement.probeItems, generatable, importance)) say(`| ${g} | ${o.id.replace("abrsm2020.", "")} | ${o.domain} | ${importance.get(o.id)} | ${o.statement} |`);
say();
if (write) writeFileSync(join(import.meta.dirname, "../../../docs/curriculum/PRACTICE_EXAM_COVERAGE.md"), out.join("\n") + "\n");
if (failed) {
  console.error(`\n${failed} coverage problem(s)`);
  process.exit(1);
}
