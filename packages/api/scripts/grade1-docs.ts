/**
 * Generates the Grade 1 completion audit and the teacher review pack from live data (never hand-edited).
 * Run: npm run docs:grade1 -w @mtp/api
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { effectiveScope } from "@mtp/curriculum";
import { generateItem, solutionFor } from "@mtp/engine";
import { createApp } from "../src/app.ts";
import { loadCourse } from "../src/course.ts";
import { openDb } from "../src/db.ts";
import { auditCapacity, MIN_DISTINCT, shortfalls } from "../src/mastery-audit.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const course = loadCourse();
const ix = course.ix;
const app = createApp({ db: openDb(":memory:"), course });
const G1 = course.nodes.filter((n) => n.grade === 1);
const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const cap = auditCapacity(course, app.nodes, 1, 400);

// ---------------------------------------------------------------- completion audit
const a: string[] = [];
a.push("# Grade 1 completion audit (Brief 05)", "", "_Generated by `npm run docs:grade1 -w @mtp/api` from the committed content; do not edit by hand._", "");
a.push("**Status: development-complete, teacher sign-off pending.** Nothing here is approved for public educational release. Every lesson, template and generated item is `draft` / unreviewed until a qualified music teacher signs it off (see the teacher review pack).", "");
a.push("## 1. Nodes", "");
const count = (t: string) => G1.filter((n) => n.type === t).length;
a.push(`| Type | Nodes | Playable |`, `|---|---|---|`);
for (const [t, label] of [["lesson", "Lessons"], ["practice", "Unit practice"], ["review", "Unit review"], ["unit_challenge", "Unit challenges"], ["grade_assessment", "Grade 1 assessment"]] as const) {
  a.push(`| ${label} | ${count(t)} | ${G1.filter((n) => n.type === t && course.isPlayable(n.id)).length} |`);
}
a.push(`| **Total** | **${G1.length}** | **${G1.filter((n) => course.isPlayable(n.id)).length}** |`, "");
a.push("Lessons are fixed authored content (`content/lessons/G1-*.json`, generated from `packages/api/scripts/grade1/*.ts` by `npm run author:grade1`). Practice, review, challenge and assessment nodes are built by the server per learner from the lessons' exercise bindings and `content/assessments/grade-1.json`, graded by the deterministic engine.", "");

a.push("## 2. Official outcomes (ABRSM 2020 Grade 1) → teaching, practice, revision, assessment", "");
a.push("| Outcome | Statement | Taught by | Unit challenge / assessment sections | Eligible for revision (concepts with a generator template) |", "|---|---|---|---|---|");
const outs = [...ix.outcomes.values()].filter((o) => o.grade === 1).sort((x, y) => x.id.localeCompare(y.id));
const assessed = (oid: string) => [...ix.assessments.values()].filter((as) => as.sections.some((s) => s.outcomeIds.includes(oid))).map((as) => as.id);
for (const o of outs) {
  const taught = (ix.outcomeTaughtBy.get(o.id) ?? []).map((n) => n.id.replace("G1-", ""));
  const concepts = [...ix.concepts.values()].filter((c) => c.outcomeIds.includes(o.id));
  const revisable = concepts.filter((c) => (cap.find((r) => r.conceptId === c.id)?.distinct ?? 0) > 0).length;
  a.push(`| ${o.id.replace("abrsm2020.", "")} | ${esc(o.statement)} | ${taught.join(", ")} | ${assessed(o.id).join(", ")} | ${revisable}/${concepts.length} |`);
}
a.push("", `Uncovered outcomes: **${outs.filter((o) => !(ix.outcomeTaughtBy.get(o.id) ?? []).length || !assessed(o.id).length).length}**.`, "");

a.push("## 3. Reference-book sections (First Steps, Grade 1, sections 1-19) → lessons", "");
a.push("| Section | Heading | Printed page | Lessons using it | Source note |", "|---|---|---|---|---|");
const secs = ix.c.book.sections.filter((s) => s.grade === 1).sort((x, y) => x.section - y.section);
for (const s of secs) {
  const lessons = G1.filter((n) => n.type === "lesson" && n.bookSectionIds.includes(s.id)).map((n) => n.id.replace("G1-", ""));
  a.push(`| ${s.section} | ${esc(s.heading)} | ${s.printedPage} | ${lessons.join(", ") || "-"} | topic pointer only; no text or example reused |`);
}
a.push("", `Sections without a lesson: **${secs.filter((s) => !G1.some((n) => n.type === "lesson" && n.bookSectionIds.includes(s.id))).length}**.`, "");

a.push("## 4. Concepts → explanation, independent practice, mastery capacity", "");
a.push(`Brief 04's thresholds are unchanged (proficient: 4 distinct correct across 2 templates; mastered: 8 across 2 templates over 3 days plus a delayed review). The test \`mastery-audit.test.ts\` fails if any concept has fewer than ${MIN_DISTINCT} distinct questions or fewer than two question types with at least 3 each.`, "");
a.push("| Concept | Taught in | Question types (distinct questions each) | Total distinct |", "|---|---|---|---|");
for (const c of [...ix.concepts.values()].filter((x) => x.grade === 1)) {
  const r = cap.find((x) => x.conceptId === c.id)!;
  const taught = (ix.conceptTaughtBy.get(c.id) ?? []).map((n) => n.id.replace("G1-", ""));
  a.push(`| ${c.id} | ${taught.join(", ")} | ${Object.entries(r.templates).map(([t, n]) => `${t.replace("t.g1.", "")} ${n}`).join(", ")} | ${r.distinct} |`);
}
const short = shortfalls(cap);
a.push("", `Concepts below the capacity rule: **${short.length}**${short.length ? ": " + short.map((s) => s.conceptId).join(", ") : ""}.`, "");
a.push("**Honest limits of the counts.** Distinct means a different question identity (template, prompt, music, answer; option order is ignored). For the vocabulary concepts the number of underlying *facts* is small (for example three articulation terms), so their variety comes from the direction of the question (term to meaning, meaning to term, sign to meaning, term in a melody) and from different distractor sets, not from many different facts. The teacher is asked whether the Grade 1 term lists are complete (see Q2).", "");

a.push("## 5. Lessons", "");
a.push("| Lesson | Title | Guided | Independent | Concepts | Content version |", "|---|---|---|---|---|---|");
for (const n of G1.filter((x) => x.type === "lesson")) {
  const l = course.lesson(n.id)!;
  a.push(`| ${n.id} | ${esc(n.title)} | ${l.items.filter((i) => i.section === "guided").length} | ${l.items.filter((i) => i.section === "independent").length} | ${n.conceptIds.length} | ${n.contentVersion} |`);
}
a.push("", "## 6. Assessments", "");
a.push("| Node | Blueprint | Sections | Questions per run |", "|---|---|---|---|");
for (const n of G1.filter((x) => x.assessmentId)) {
  const b = ix.assessments.get(n.assessmentId!)!;
  a.push(`| ${n.id} | ${b.id} v${b.version} | ${b.sections.length} | ${b.sections.reduce((t, s) => t + s.itemCount, 0)} |`);
}
a.push("", `Pass marks (provisional, in \`content/policy/progression.json\`): unit challenge ${ix.c.policy.assessments?.unitChallengePassPercent}%, Grade 1 assessment ${ix.c.policy.assessments?.gradePassPercent}%. They are in-app practice marks, not ABRSM marks. A run below the mark is stored as an honest result and completes nothing; completing the grade requires a passed assessment run.`, "");

a.push("## 7. Source verification", "");
a.push("| Source | Status |", "|---|---|");
a.push("| Official ABRSM Music Theory syllabus outline from 2020 (`music-theory-syllabus-outline-grades-1-5-from-2020.pdf`, abrsm.org) | Downloaded and read on 2026-11-10. Grade 1 text matches `content/syllabus/abrsm-2020-outcomes.json` (note values and rests incl. the alternative terms 'whole note', 'half note'; ties; single dots; 2/4, 3/4, 4/4; bar-lines and grouping; stave, treble and bass clefs, middle C; sharps, flats, naturals; major scale construction; keys C, G, D, F with tonic triads, degrees and intervals above the tonic; terms and signs; simple melody questions). |");
a.push("| Is the 2020 syllabus still current? | ABRSM's Music Theory pages (searched 2026-11-10) state the syllabus is valid from 2020 until further notice, and that Grades 1-5 are now taken online (75 marks, pass 50). Recorded as 'currently valid per ABRSM web pages'; Q1 stays open for a human to confirm against the live syllabus page. |");
a.push("| Term lists | The outline does not enumerate terms. The provisional vocabulary is unchanged. Differences from the reference book's Grade 1 list are in the teacher pack. |");
a.push("| Reference book (Eric Taylor, First Steps in Music Theory) | The supplied PDF was text-extracted. The contents page lists sections 1-19 and the page offsets in `first-steps-sections.json` (printed page 1 = scan page 8, printed 27 = scan 21) agree with the extracted pages checked (printed 1, 2, 4, 27-28). Not every page was compared. No book text, example or illustration is reused; sections are subject pointers. |");
a.push("| Teacher / originality | Teacher review: **pending**. All teaching copy, notation and melodies are newly written; the melody in G1-U7-L05 is composed for this course. |", "");
mkdirSync(join(root, "docs/curriculum"), { recursive: true });
writeFileSync(join(root, "docs/curriculum/GRADE_1_COMPLETION_AUDIT.md"), a.join("\n") + "\n");

// ---------------------------------------------------------------- teacher review pack
const t: string[] = [];
t.push("# Grade 1 teacher review pack (Brief 05)", "", "_Generated by `npm run docs:grade1 -w @mtp/api`. **Review status: pending. No teacher has reviewed or approved any of this material.**_", "");
t.push("Please mark each section Agree / Change / Reject, and answer the decisions in section 8. Every generated question below can be reproduced from its template, seed and scope.", "");
t.push("## 1. Syllabus coverage", "", "See `GRADE_1_COMPLETION_AUDIT.md` sections 2-4 for outcome-to-lesson, outcome-to-assessment and concept-capacity tables.", "");
t.push("## 2. A representative lesson from each unit", "");
for (const id of ["G1-U1-L06", "G1-U2-L04", "G1-U3-L04", "G1-U4-L03", "G1-U5-L03", "G1-U6-L01", "G1-U7-L05"]) {
  const l = course.lesson(id)!;
  const n = ix.nodeById.get(id)!;
  t.push(`### ${id}: ${n.title}`, "", `**Objective.** ${l.objective.statement}`, "");
  for (const b of l.explanation) t.push(`- ${b.kind === "notation" ? `[notation] ${b.caption}` : b.text}`);
  t.push("", "**Recap.** " + l.recap.join(" | "), "");
}
t.push("## 3. Generated-question samples (seeds 1-4 per template, in the scope of their first lesson)", "");
t.push("| Template | Seed | Question | Correct answer (engine) |", "|---|---|---|---|");
const seen = new Set<string>();
for (const n of G1.filter((x) => x.type === "lesson")) {
  for (const b of n.exercises) {
    if (seen.has(b.templateId)) continue;
    seen.add(b.templateId);
    const scope = effectiveScope(ix, n, b);
    let shown = 0;
    for (let seed = 1; seed < 60 && shown < 4; seed++) {
      try {
        const it = generateItem(ix, b.templateId, seed, { scope }).item;
        t.push(`| ${b.templateId.replace("t.g1.", "")} (${n.id.replace("G1-", "")}) | ${seed} | ${esc(it.prompt)}${it.music ? ` _Shown: ${esc(it.music.textAlternative)}_` : ""} | ${esc(solutionFor(ix, it, scope))} |`);
        shown++;
      } catch {
        /* a seed that cannot make a question is skipped */
      }
    }
  }
}
t.push("");
t.push("## 4. Notation, grouping and rest conventions the rule set enforces (please confirm each is Grade 1)", "",
  "- Beam short notes in groups that fill one beat; do not beam across the middle of a 4/4 bar.",
  "- Give each beat its own rest; in 4/4 a minim rest may fill beats 1-2 or beats 3-4; a minim rest across beats 2-3 is rejected. In 3/4 a minim rest is currently rejected (EXERCISE_ENGINE section 10).",
  "- Do not tie two notes inside a bar when one note could be written (unnecessary tie). Ties across a bar-line are allowed.",
  "- An accidental lasts to the end of the bar, on its own line or space only; a tied note keeps its accidental across the bar-line.",
  "- Scale spelling: each letter name once, in order; B flat, never A sharp; enharmonic substitutions are rejected where spelling is assessed.",
  "- Intervals are named by number only (the lower note is always the tonic); triads are root-position tonic triads only.",
  "- Stem direction is mentioned in G1-U3-L07 for neatness but never assessed.", "");
t.push("## 5. Terms and signs used (provisional list in `packages/curriculum/src/music/vocabulary.ts`)", "", "| Category | Terms at Grade 1 |", "|---|---|");
const { music } = await import("@mtp/curriculum");
const cats = new Map<string, string[]>();
for (const term of music.termsUpTo(1)) cats.set(term.category, [...(cats.get(term.category) ?? []), `${term.term} (${term.meaning})`]);
for (const [c, list] of cats) t.push(`| ${c} | ${esc(list.join("; "))} |`);
t.push("", "**Where there was doubt, the content is included.** The reference book (read for verification only) also lists _poco_, _dal segno_, _ritenuto_, _8va_ and metronome marks at Grade 1, and the 2020 outline does not enumerate terms, so these are all INCLUDED in the vocabulary and taught in G1-U7-L03 (the teacher may remove any). The course also includes _dolce_, which is not in the book's Grade 1 list. Crescendo and diminuendo are taught as words because the renderer does not yet draw hairpin signs. See Q2 and Q16.", "");
t.push("## 6. Assessment questions and scoring", "");
for (const n of G1.filter((x) => x.assessmentId)) {
  const b = ix.assessments.get(n.assessmentId!)!;
  t.push(`### ${n.id}: ${b.title} (blueprint ${b.id} v${b.version})`, "");
  for (const s of b.sections) t.push(`- ${s.title}: ${s.itemCount} question(s) from ${s.templateIds.map((x) => x.replace("t.g1.", "")).join(", ")} (outcome ${s.outcomeIds.map((o) => o.replace("abrsm2020.", "")).join(", ")})`);
  t.push("");
}
t.push(`**Scoring.** One mark for each question answered correctly at the first attempt, with no hints and no second tries. Pass marks (provisional): unit challenge ${ix.c.policy.assessments?.unitChallengePassPercent}%, Grade 1 assessment ${ix.c.policy.assessments?.gradePassPercent}%. These are in-app marks and are never shown as ABRSM marks; every result screen carries the 'not an ABRSM examination' statement.`, "");
t.push("## 7. Known ambiguities and limitations", "",
  "- Teacher review of every lesson, template, vocabulary list and the golden answer tables is outstanding (all content is `draft`).",
  "- The common-time sign (C) is taught in words only; hairpins, repeat marks and 8va are not drawn by the renderer.",
  "- Articulation (three terms) and several other concepts rest on few underlying facts; see the audit's honest-limits note.",
  "- The sounds are synthesised tones, not instruments. No novice learner test has been run.",
  "- Questions are generated per learner; individual generated variants are not teacher-reviewed one by one, only the templates and samples above.", "");
t.push("## 8. Decisions needed", "",
  "1. Confirm the Grade 1 term lists (Q2, Q16). Everything in doubt is already included (_dolce_, _poco_, _dal segno_, _ritenuto_, _8va_, metronome marks); say which to remove.",
  "2. Confirm the beaming rule 'keep the middle of a 4/4 bar visible' is Grade 1, not Grade 2.",
  "3. Confirm the rest conventions in section 4, especially the 3/4 minim rest (Q3).",
  "4. Confirm the provisional pass marks (70% challenge, 66% assessment) and the mastery thresholds (Q11).",
  "5. Confirm whether tied notes across bar-lines and accidentals through ties are assessed at Grade 1.",
  "6. Sign off, or list changes for, the teaching copy of each lesson.", "");
mkdirSync(join(root, "docs/teacher"), { recursive: true });
writeFileSync(join(root, "docs/teacher/GRADE_1_TEACHER_REVIEW_PACK.md"), t.join("\n") + "\n");
console.log("wrote docs/curriculum/GRADE_1_COMPLETION_AUDIT.md and docs/teacher/GRADE_1_TEACHER_REVIEW_PACK.md");
